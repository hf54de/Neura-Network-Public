    def __init__(self, language_code=None, language_file_path=None):
        self.language_file_path = (
            Path(language_file_path)
            if language_file_path
            else self.find_language_file()
        )
        self.languages = {
            "en": {
                "name": "English",
                "help_file": "hilfe_en.md",
                "texts": deepcopy(self.BUILTIN_ENGLISH)
            }
        }
        self.load_language_file()
        self.current_language = self.normalize_language(language_code)

    @staticmethod
    def resource_directories():
        directories = []
        temporary_directory = getattr(sys, "_MEIPASS", None)

        if temporary_directory:
            directories.append(Path(temporary_directory))

        directories.extend(
            [
                Path(__file__).resolve().parent,
                Path.cwd()
            ]
        )

        unique_directories = []

        for directory in directories:
            if directory not in unique_directories:
                unique_directories.append(directory)

        return unique_directories

    @classmethod
    def find_language_file(cls):
        for directory in cls.resource_directories():
            candidate = directory / cls.LANGUAGE_FILE_NAME

            if candidate.is_file():
                return candidate

        return cls.resource_directories()[0] / cls.LANGUAGE_FILE_NAME

    def load_language_file(self):
        try:
            data = json.loads(
                self.language_file_path.read_text(encoding="utf-8")
            )
        except (OSError, json.JSONDecodeError, TypeError, ValueError):
            return

        language_blocks = data.get("languages")

        if not isinstance(language_blocks, dict):
            return

        for language_code, block in language_blocks.items():
            if not isinstance(language_code, str) or not isinstance(block, dict):
                continue

            language_code = language_code.strip().lower()

            if not language_code:
                continue

            existing = self.languages.get(
                language_code,
                {"name": language_code, "help_file": "", "texts": {}}
            )
            texts = dict(existing["texts"])
            loaded_texts = block.get("texts")

            if isinstance(loaded_texts, dict):
                texts.update(
                    {
                        key: value
                        for key, value in loaded_texts.items()
                        if (
                            isinstance(key, str)
                            and isinstance(value, str)
                            and not key.startswith("__section_")
                        )
                    }
                )

            name = block.get("name")
            help_file = block.get("help_file")
            self.languages[language_code] = {
                "name": name if isinstance(name, str) and name.strip() else existing["name"],
                "help_file": (
                    help_file
                    if isinstance(help_file, str) and help_file.strip()
                    else existing["help_file"]
                ),
                "texts": texts
            }

    def normalize_language(self, language_code):
        if isinstance(language_code, str):
            language_code = language_code.strip().lower()

            if language_code in self.languages:
                return language_code

        return self.DEFAULT_LANGUAGE

    def available_languages(self):
        return [
            (code, block["name"])
            for code, block in self.languages.items()
        ]

    def text(self, key, **values):
        current_texts = self.languages.get(
            self.current_language,
            {}
        ).get("texts", {})
        english_texts = self.languages["en"]["texts"]
        text = current_texts.get(
            key,
            english_texts.get(key, key)
        )

        if not values:
            return text

        try:
            return text.format(**values)
        except (KeyError, ValueError, IndexError):
            return text

    def find_help_file(self):
        help_names = []
        current_block = self.languages.get(self.current_language, {})

        for name in (
            current_block.get("help_file"),
            self.languages["en"].get("help_file"),
            "hilfe.md"
        ):
            if isinstance(name, str) and name and name not in help_names:
                help_names.append(name)

        for directory in self.resource_directories():
            for help_name in help_names:
                candidate = directory / help_name

                if candidate.is_file():
                    return candidate

        return self.resource_directories()[0] / help_names[0]
